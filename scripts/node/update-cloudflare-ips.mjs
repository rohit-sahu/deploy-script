#!/usr/bin/env node

// Re-fetches Cloudflare's published edge IP ranges and regenerates
// nginx/cloudflare-ips.conf (used by https.cloudflare.conf.template when
// CLOUDFLARE_PROXIED=1 -- see RUNNING.md). Only touches that one file; the
// rest of the nginx config/templates are untouched.
//
// Usage:
//   npm run cloudflare-ips:update            # fetch + write if changed, then
//                                             # reload nginx if it's running
//   npm run cloudflare-ips:update -- --check  # exit 1 if an update is
//                                             # available, without writing
//                                             # (for a cron job/CI check)
//
// No dependencies beyond Node's built-in https/fs -- safe to run directly
// with `node scripts/node/update-cloudflare-ips.mjs` even after
// `npm run build` has removed node_modules.

import https from "node:https";
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
// Robust to being run either from source (scripts/node/update-cloudflare-ips.mjs,
// two levels below repo root) or from the bundled dist/update-cloudflare-ips.mjs
// (one level below repo root, see build.mjs) -- picks whichever candidate
// actually contains package.json, rather than hardcoding one "..".
function findRoot(startDir) {
  const candidates = [path.join(startDir, ".."), path.join(startDir, "..", "..")];
  for (const candidate of candidates) {
    if (fs.existsSync(path.join(candidate, "package.json"))) return candidate;
  }
  return candidates[candidates.length - 1];
}
const ROOT = findRoot(__dirname);
const OUT_FILE = path.join(ROOT, "nginx", "cloudflare-ips.conf");

const SOURCES = {
  v4: "https://www.cloudflare.com/ips-v4",
  v6: "https://www.cloudflare.com/ips-v6",
};

const CHECK_ONLY = process.argv.includes("--check");

function fetchText(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, { headers: { "User-Agent": "deploy-script/cloudflare-ips-updater" } }, (res) => {
        if (res.statusCode !== 200) {
          reject(new Error(`${url} responded with HTTP ${res.statusCode}`));
          res.resume();
          return;
        }
        let body = "";
        res.setEncoding("utf8");
        res.on("data", (chunk) => (body += chunk));
        res.on("end", () => resolve(body));
      })
      .on("error", reject);
  });
}

function parseRanges(text) {
  return text
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);
}

function buildConfig(v4Ranges, v6Ranges) {
  const lines = [
    "# Cloudflare's published edge IP ranges — used by ngx_http_realip_module",
    "# (see https.cloudflare.conf.template) to resolve the true visitor IP from",
    "# CF-Connecting-IP instead of trusting the TCP-level $remote_addr (which,",
    "# when Cloudflare's proxy/orange-cloud DNS is in front of this nginx, is",
    "# always one of Cloudflare's own edge IPs, not the visitor's).",
    "#",
    "# Only loaded when CLOUDFLARE_PROXIED=1 (see docker-entrypoint.sh).",
    "#",
    `# Auto-generated by scripts/node/update-cloudflare-ips.mjs on ${new Date().toISOString().slice(0, 10)}`,
    "# from https://www.cloudflare.com/ips-v4 and -v6 — do not edit by hand,",
    "# re-run `npm run cloudflare-ips:update` instead (see RUNNING.md).",
    ...v4Ranges.map((r) => `set_real_ip_from ${r};`),
    ...v6Ranges.map((r) => `set_real_ip_from ${r};`),
    "real_ip_header CF-Connecting-IP;",
    "real_ip_recursive off;",
    "",
  ];
  return lines.join("\n");
}

// Ignores the "Auto-generated ... on <date>" line when comparing, so a
// same-day re-run (or a run where the ranges genuinely haven't changed)
// doesn't report a "change" that's just today's date stamp.
function normalizeForCompare(content) {
  return content
    .split("\n")
    .filter((line) => !line.startsWith("# Auto-generated by"))
    .join("\n");
}

function nginxIsRunning() {
  try {
    const out = execFileSync("docker", ["compose", "ps", "-q", "nginx"], {
      cwd: ROOT,
      encoding: "utf8",
    }).trim();
    return out.length > 0;
  } catch {
    return false;
  }
}

async function main() {
  console.log("==> Fetching Cloudflare IP ranges...");
  const [v4Text, v6Text] = await Promise.all([
    fetchText(SOURCES.v4),
    fetchText(SOURCES.v6),
  ]);
  const v4Ranges = parseRanges(v4Text);
  const v6Ranges = parseRanges(v6Text);

  if (v4Ranges.length === 0 || v6Ranges.length === 0) {
    throw new Error("Fetched an empty IP range list -- refusing to write a possibly-broken config.");
  }

  const newConfig = buildConfig(v4Ranges, v6Ranges);
  const existingConfig = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, "utf8") : "";
  const changed = normalizeForCompare(newConfig) !== normalizeForCompare(existingConfig);

  if (!changed) {
    console.log(`==> Already up to date (${v4Ranges.length} IPv4 + ${v6Ranges.length} IPv6 ranges) -- no changes.`);
    return;
  }

  if (CHECK_ONLY) {
    console.log("==> Cloudflare's IP ranges have changed -- run `npm run cloudflare-ips:update` to apply.");
    process.exitCode = 1;
    return;
  }

  fs.writeFileSync(OUT_FILE, newConfig);
  console.log(`==> Updated ${path.relative(ROOT, OUT_FILE)} (${v4Ranges.length} IPv4 + ${v6Ranges.length} IPv6 ranges).`);

  if (nginxIsRunning()) {
    console.log("==> Reloading nginx to pick up the change...");
    execFileSync("docker", ["compose", "exec", "nginx", "nginx", "-s", "reload"], {
      cwd: ROOT,
      stdio: "inherit",
    });
    console.log("==> nginx reloaded.");
  } else {
    console.log("==> nginx isn't currently running (or docker compose isn't available here) -- it'll pick up the new file on next start/restart.");
  }
}

main().catch((err) => {
  console.error(`\n${err.message}`);
  process.exitCode = 1;
});
